<?php

namespace Tests\Feature\Billing;

use App\Models\ClientAgreement;
use App\Models\ClientInvoice;
use App\Services\Billing\ClientInvoicingService;
use App\Services\Billing\InvoiceDocumentService;
use App\Services\Billing\InvoiceLifecycleService;
use App\Support\Billing\InvoiceLineDetail;
use Carbon\Carbon;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\Concerns\BuildsGoldenInvoices;
use Tests\Support\Billing\BladeInvoiceDocumentFacts;
use Tests\Support\Billing\InvoiceDocumentFacts;
use Tests\TestCase;

/**
 * The hours statement is the snapshot stored with the invoice, not a reading
 * of the ledger at render time.
 *
 * A December and a January invoice are generated by the real generator and
 * issued. The ledger is then changed underneath January - an earlier month's
 * time is edited and added to, and the agreement's retainer is changed - and
 * the January document is rendered again. Its figures must not move, for
 * either audience.
 */
class InvoiceDocumentIssuedSnapshotGoldenTest extends TestCase
{
    use BuildsGoldenInvoices;
    use RefreshDatabase;

    private ClientAgreement $agreement;

    protected function setUp(): void
    {
        parent::setUp();
        $this->setUpGoldenTenant();
        $this->travelTo(Carbon::parse('2026-02-20 12:00:00'));
        $this->agreement = ClientAgreement::query()->create([
            'workspace_id' => $this->workspace->id, 'client_company_id' => $this->company->id, 'title' => 'Synthetic retainer',
            'status' => 'active', 'currency' => 'USD', 'starts_on' => '2025-12-01',
            'retainer_minutes' => 600, 'retainer_amount' => 150000, 'catch_up_threshold_minutes' => 60,
            'hourly_rate_amount' => 15000, 'billing_cadence' => 'monthly', 'rollover_months' => 1,
        ]);
    }

    protected function documentFacts(): InvoiceDocumentFacts
    {
        return new BladeInvoiceDocumentFacts(app(InvoiceDocumentService::class));
    }

    /** @return iterable<string, array{string}> */
    public static function audiences(): iterable
    {
        yield 'operator' => [InvoiceLineDetail::OPERATOR];
        yield 'client' => [InvoiceLineDetail::CLIENT];
    }

    /** @return array{0: ClientInvoice, 1: int} the issued January invoice, and the December entry's id */
    private function issuedJanuary(): array
    {
        $december = $this->goldenEntry('2025-12-10', 300);
        $this->goldenEntry('2026-01-05', 450);
        $this->goldenEntry('2026-01-20', 360);

        $invoicing = app(ClientInvoicingService::class);
        $lifecycle = app(InvoiceLifecycleService::class);
        $first = $invoicing->generateInvoice($this->company, Carbon::parse('2025-12-01'), Carbon::parse('2025-12-31'), $this->agreement);
        $lifecycle->issue($first, $this->workspace);
        $draft = $invoicing->generateInvoice($this->company, Carbon::parse('2026-01-01'), Carbon::parse('2026-01-31'), $this->agreement);
        $issued = $lifecycle->issue($draft, $this->workspace);

        return [$issued->fresh() ?? $issued, $december->id];
    }

    #[DataProvider('audiences')]
    public function test_the_statement_does_not_move_when_an_earlier_month_or_the_agreement_changes_after_issue(string $audience): void
    {
        [$january, $decemberEntry] = $this->issuedJanuary();

        $before = $this->documentFacts()->extract($january, $audience);
        $this->assertNotNull($before['hours_statement']);
        $this->assertNotEmpty($before['hours_statement']['sections']);
        $storedBefore = $january->hours_statement;

        // The ledger moves: December shrinks, more December time appears, and the
        // retainer doubles. A re-derived statement would now disagree.
        DB::table('client_time_entries')->where('id', $decemberEntry)->update(['minutes' => 60]);
        $this->goldenEntry('2025-12-20', 900);
        $this->agreement->forceFill(['retainer_minutes' => 1200, 'retainer_amount' => 300000])->save();

        $reread = ClientInvoice::query()->whereKey($january->id)->firstOrFail();
        $this->assertSame($storedBefore, $reread->hours_statement, 'The stored snapshot is untouched.');
        $this->assertSame(60, (int) DB::table('client_time_entries')->where('id', $decemberEntry)->value('minutes'), 'The ledger did change.');

        $after = $this->documentFacts()->extract($reread, $audience);

        $this->assertSame($before['hours_statement'], $after['hours_statement']);
        $this->assertSame($before['lines'], $after['lines']);
        $this->assertSame($before['totals'], $after['totals']);
    }

    /**
     * Not frozen, and pinned as such: Appendix A is read from the time entries
     * attached to each line when the document renders, so an edit to an
     * attached entry's minutes changes the appendix while the statement and the
     * line stay put. A rewrite either keeps this or freezes the appendix on
     * purpose.
     */
    public function test_appendix_a_reads_the_attached_entries_live_unlike_the_statement(): void
    {
        [$january] = $this->issuedJanuary();
        $before = $this->documentFacts()->extract($january, InvoiceLineDetail::OPERATOR);
        $this->assertNotNull($before['appendix']);

        DB::table('client_time_entries')->where('worked_on', '2026-01-05')->update(['minutes' => 30]);
        $after = $this->documentFacts()->extract($january, InvoiceLineDetail::OPERATOR);

        $this->assertNotSame($before['appendix'], $after['appendix']);
        $this->assertSame($before['hours_statement'], $after['hours_statement']);
        $this->assertSame($before['lines'], $after['lines']);
    }
}
